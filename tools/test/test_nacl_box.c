static const vec_t kVecs[] = {
    { "empty", kM0, 0, kC0, 16 },
    { "disco-magic", kM1, 8, kC1, 24 },
    { "1..63", kM2, 63, kC2, 79 },
    { "113B", kM3, 113, kC3, 129 },
};

int main(void)
{
    uint8_t buf[256];
    for (size_t i = 0; i < sizeof(kVecs) / sizeof(kVecs[0]); i++) {
        const vec_t *v = &kVecs[i];
        char name[64];
        /* seal A→B must equal libsodium byte for byte */
        memset(buf, 0xAA, sizeof(buf));
        int rc = nacl_box(buf, v->m, v->mlen, kNonce, kPkB, kSkA);
        snprintf(name, sizeof(name), "seal/%s", v->name);
        CHECK(name, rc == 0 && memcmp(buf, v->c, v->clen) == 0);
        /* open B←A with the libsodium ciphertext */
        memset(buf, 0xAA, sizeof(buf));
        rc = nacl_box_open(buf, v->c, v->clen, kNonce, kPkA, kSkB);
        snprintf(name, sizeof(name), "open/%s", v->name);
        CHECK(name, rc == 0 && (v->mlen == 0 || memcmp(buf, v->m, v->mlen) == 0));
        /* precomputed-shared path must agree */
        uint8_t k[32];
        rc = nacl_box_compute_shared(k, kPkA, kSkB);
        memset(buf, 0xAA, sizeof(buf));
        int rc2 = nacl_box_open_after_shared(buf, v->c, v->clen, kNonce, k);
        snprintf(name, sizeof(name), "open-shared/%s", v->name);
        CHECK(name, rc == 0 && rc2 == 0 && (v->mlen == 0 || memcmp(buf, v->m, v->mlen) == 0));
        /* tamper: flip one tag bit → must fail */
        uint8_t bad[256]; memcpy(bad, v->c, v->clen); bad[0] ^= 0x01;
        snprintf(name, sizeof(name), "tamper/%s", v->name);
        CHECK(name, nacl_box_open(buf, bad, v->clen, kNonce, kPkA, kSkB) != 0);
    }
    if (g_fail) { printf("\nFAIL\n"); return 1; }
    printf("\n[PASS] all nacl_box assertions passed\n");
    return 0;
}
