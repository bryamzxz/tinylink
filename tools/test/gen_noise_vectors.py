"""Regenerate the ts2021 Noise IK vectors embedded in test_noise_ik.c.

An implementation of Noise_IK_25519_ChaChaPoly_BLAKE2s as Tailscale's
controlbase runs it (nonce = 4 zero bytes || BE64 counter, not the Noise
spec's LE64), written from the spec on top of `cryptography` (OpenSSL:
X25519, ChaCha20-Poly1305) and hashlib.blake2s — none of tinylink's own
crypto. Requires `pip install cryptography`.

Inputs are SHA-256 of fixed strings; the initiator ephemeral is what the
test's esp_fill_random() stub returns (the same SHA-256), clamped as
curve25519_keypair() does. Record plaintexts follow pt_bytes(). Short
records are printed in full, long ones as BLAKE2s-256 of the ciphertext.
"""
import hashlib
import hmac
import struct

from cryptography.hazmat.primitives.asymmetric.x25519 import (
    X25519PrivateKey, X25519PublicKey)
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives import serialization

NAME = b"Noise_IK_25519_ChaChaPoly_BLAKE2s"
PROLOGUE = b"Tailscale Control Protocol v1"
C2S_LENS = [0, 1, 15, 16, 17, 64, 65, 300, 4080]
S2C_LENS = [0, 5, 64, 1000, 4080]
FAR_N = 0x0102030405060708
FULL_MAX = 65


def sha(s):
    return hashlib.sha256(s).digest()


def clamp(k):
    k = bytearray(k)
    k[0] &= 0xF8
    k[31] &= 0x7F
    k[31] |= 0x40
    return bytes(k)


def pub(priv):
    raw = serialization.Encoding.Raw
    return X25519PrivateKey.from_private_bytes(priv).public_key().public_bytes(
        raw, serialization.PublicFormat.Raw)


def dh(priv, peer):
    return X25519PrivateKey.from_private_bytes(priv).exchange(
        X25519PublicKey.from_public_bytes(peer))


def H(*parts):
    h = hashlib.blake2s(digest_size=32)
    for p in parts:
        h.update(p)
    return h.digest()


def hmac_b2s(key, data):
    return hmac.new(key, data, lambda: hashlib.blake2s(digest_size=32)).digest()


def hkdf2(ck, ikm):
    t0 = hmac_b2s(ck, ikm)
    t1 = hmac_b2s(t0, b"\x01")
    t2 = hmac_b2s(t0, t1 + b"\x02")
    return t1, t2


def nonce(n):
    return b"\x00" * 4 + struct.pack(">Q", n)


def seal(k, n, ad, pt):
    return ChaCha20Poly1305(k).encrypt(nonce(n), pt, ad or None)


def open_(k, n, ad, ct):
    return ChaCha20Poly1305(k).decrypt(nonce(n), ct, ad or None)


def pt_bytes(length, dirtag):
    return bytes(((i * 31 + length + dirtag) & 0xFF) for i in range(length))


s_priv = sha(b"tinylink-noise-kat-machine")
c_priv = sha(b"tinylink-noise-kat-control")
e_priv = clamp(sha(b"tinylink-noise-kat-ephemeral"))
re_priv = sha(b"tinylink-noise-kat-control-ephemeral")
s_pub, c_pub, e_pub, re_pub = pub(s_priv), pub(c_priv), pub(e_priv), pub(re_priv)

# Initiator (= noise_ik.c) — msg1: -> e, es, s, ss.
h = H(NAME) if len(NAME) > 32 else NAME.ljust(32, b"\x00")
ck = h
h = H(h, PROLOGUE)
h = H(h, c_pub)
h = H(h, e_pub)
ck, k = hkdf2(ck, dh(e_priv, c_pub))
ct_s = seal(k, 0, h, s_pub)
h = H(h, ct_s)
ck, k = hkdf2(ck, dh(s_priv, c_pub))
ct_p = seal(k, 0, h, b"")
h = H(h, ct_p)
msg1 = e_pub + ct_s + ct_p
assert len(msg1) == 96

# Responder — msg2: <- e, ee, se.
h = H(h, re_pub)
ck, k = hkdf2(ck, dh(re_priv, e_pub))
ck, k = hkdf2(ck, dh(re_priv, s_pub))
tag = seal(k, 0, h, b"")
msg2 = re_pub + tag
k_send, k_recv = hkdf2(ck, b"")      # initiator's view of Split()


def hexc(x):
    return ", ".join("0x%02x" % c for c in x)


print("/* generated by gen_noise_vectors.py */")
for name, v in [("kMachinePriv", s_priv), ("kControlPriv", c_priv),
                ("kEphemeralSeed", sha(b"tinylink-noise-kat-ephemeral")),
                ("kControlEphPriv", re_priv), ("kMsg1", msg1), ("kMsg2", msg2),
                ("kSplitSend", k_send), ("kSplitRecv", k_recv)]:
    print("static const uint8_t %s[%d] = { %s };" % (name, len(v), hexc(v)))

for direction, key, lens, tag_ in [("C2S", k_send, C2S_LENS, 0x00),
                                   ("S2C", k_recv, S2C_LENS, 0x80)]:
    for n, ln in enumerate(lens):
        ct = seal(key, n, b"", pt_bytes(ln, tag_))
        assert open_(key, n, b"", ct) == pt_bytes(ln, tag_)
        if len(ct) <= FULL_MAX:
            print("static const uint8_t k%sCt%d[%d] = { %s };"
                  % (direction, n, len(ct), hexc(ct)))
        else:
            print("static const uint8_t k%sCt%dB2s[32] = { %s };"
                  % (direction, n, hexc(H(ct))))

far = seal(k_send, FAR_N, b"", pt_bytes(17, 0x00))
print("static const uint8_t kFarCt[%d] = { %s };" % (len(far), hexc(far)))
