# Writes components/tinylink/src/bench_tls_vectors.h for
# CONFIG_TINYLINK_BENCH_TLS (round 1.3.8) from public data only:
#   - the two chains derp16b.tailscale.com serves, captured with
#       openssl s_client -connect derp16b.tailscale.com:443 \
#         -servername derp16b.tailscale.com -showcerts -tls1_2 </dev/null
#     (ECDSA chain: the default offer) and the same with
#       -cipher ECDHE-RSA-AES128-GCM-SHA256 (RSA chain), each as the
#     s_client text output;
#   - ISRG Root X1's SubjectPublicKeyInfo, taken from ESP-IDF's own
#     esp_crt_bundle/cacrt_all.pem (the key the bundle anchors X1 with);
#   - a throwaway P-256 key's public half, a SHA-256 digest and its
#     ECDSA signature (the private key is generated here and discarded:
#     the bench only verifies).
# Usage: gen_vectors.py <ecdsa_s_client.txt> <rsa_s_client.txt> <cacrt_all.pem> > header
import re
import subprocess
import sys
import tempfile
import os


def pems(path):
    txt = open(path).read()
    return re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", txt, re.S)


def run(args, data=None):
    return subprocess.run(args, input=data, capture_output=True, check=True).stdout


def der(pem):
    return run(["openssl", "x509", "-outform", "DER"], pem.encode())


def subject(pem):
    return run(["openssl", "x509", "-noout", "-subject", "-enddate"], pem.encode()).decode().strip()


def x1_spki(bundle):
    for p in pems(bundle):
        if "CN=ISRG Root X1" in subject(p).split("\n")[0]:
            pub = run(["openssl", "x509", "-pubkey", "-noout"], p.encode())
            return run(["openssl", "pkey", "-pubin", "-outform", "DER"], pub)
    raise SystemExit("ISRG Root X1 not in " + bundle)


def p256_vector():
    with tempfile.TemporaryDirectory(dir=os.getcwd()) as d:
        key, msg, dig, sig = (os.path.join(d, n) for n in ("k.pem", "m", "m.sha256", "m.sig"))
        run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", key])
        spki = run(["openssl", "ec", "-in", key, "-pubout", "-outform", "DER"])
        open(msg, "wb").write(b"tinylink bench p256")
        open(dig, "wb").write(run(["openssl", "dgst", "-sha256", "-binary", msg]))
        run(["openssl", "pkeyutl", "-sign", "-inkey", key, "-in", dig, "-out", sig])
        return spki, open(dig, "rb").read(), open(sig, "rb").read()


def arr(name, b, note):
    out = ["/* %s */" % note, "static const uint8_t %s[%d] = {" % (name, len(b))]
    for i in range(0, len(b), 16):
        out.append("    " + ",".join("0x%02x" % x for x in b[i:i + 16]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    ecdsa, rsa, bundle = sys.argv[1:4]
    e, r = pems(ecdsa), pems(rsa)
    spki, dig, sig = p256_vector()
    parts = ["// SPDX-License-Identifier: MIT",
             "// Copyright (c) 2026 Bryam (bryamzxz)",
             "//",
             "// Generated by tools/tls_bench/gen_vectors.py — public data only (see there).",
             "// Included by tinylink_bench_tls.c alone (CONFIG_TINYLINK_BENCH_TLS).",
             "",
             "#pragma once",
             "",
             "#include <stdint.h>",
             ""]
    for i, p in enumerate(e):
        parts.append(arr("k_ecdsa_%d" % i, der(p), subject(p).replace("\n", ", ")))
    for i, p in enumerate(r):
        parts.append(arr("k_rsa_%d" % i, der(p), subject(p).replace("\n", ", ")))
    parts.append(arr("k_x1_spki", x1_spki(bundle), "ISRG Root X1 SubjectPublicKeyInfo (RSA-4096), from cacrt_all.pem"))
    parts.append(arr("k_p256_spki", spki, "throwaway P-256 public key"))
    parts.append(arr("k_p256_hash", dig, "SHA-256(\"tinylink bench p256\")"))
    parts.append(arr("k_p256_sig", sig, "ECDSA P-256 signature over k_p256_hash (DER)"))
    parts.append("#define K_ECDSA_N %d" % len(e))
    parts.append("#define K_RSA_N %d" % len(r))
    head, body = parts[:10], parts[10:]
    sys.stdout.write("\n".join(head) + "\n" + "\n\n".join(body) + "\n")


if __name__ == "__main__":
    main()
